function toggleDocInvert(id) {
  const doc = document.getElementById(`doc-sheet-${id}`);
  if (doc) {
    if (doc.style.background === 'rgb(15, 23, 42)' || doc.style.background === '#0f172a') {
      doc.style.background = '#ffffff';
      doc.style.color = '#1e293b';
      const secret = document.getElementById('white-secret-text');
      if (secret) secret.style.color = '#ffffff';
    } else {
      doc.style.background = '#0f172a';
      doc.style.color = '#f1f5f9';
      const secret = document.getElementById('white-secret-text');
      if (secret) secret.style.color = '#00ff9d';
    }
  }
}

function selectDocText(id) {
  const doc = document.getElementById(id);
  if (window.getSelection && document.createRange) {
    const sel = window.getSelection();
    const range = document.createRange();
    range.selectNodeContents(doc);
    sel.removeAllRanges();
    sel.addRange(range);
  }
}

